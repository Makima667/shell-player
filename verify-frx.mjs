import fs from "node:fs";
import { compileSource } from "./src/sources/compile.js";
const P = "C:/Users/q1763/Documents/shell-player/sources/musicfree/plugins/qq-official.js";
const src = await compileSource(fs.readFileSync(P, "utf8"), { env: "desktop" });
const s = await src.search("发如雪", 1);
const target = s.list[0];
const raw = target.mf || target;
console.log("点击的条目:", raw.title, raw.artist, "mid=", raw.mid, "dur=", raw.duration);
const r = await src.getUrl(target, "high");
const usedMid = (r.url.match(/\/([MF]\d{3})([0-9A-Za-z]+)\./) || [])[2];
console.log("返回地址 mid:", usedMid, "quality:", r.quality);
const UA = "Mozilla/5.0 Chrome/126.0";
const d = await fetch(`https://c.y.qq.com/v8/fcg-bin/fcg_play_single_song.fcg?songmid=${usedMid}&format=json&platform=yqq`, { headers: { "User-Agent": UA, Referer: "https://y.qq.com/" } }).then(x => x.json()).catch(() => null);
const info = d?.data?.[0];
console.log("实际曲目:", info ? `${info.name} / ${(info.singer||[]).map(x=>x.name).join("&")} / ${info.interval}s / ${info.album?.name}` : "查询失败");
